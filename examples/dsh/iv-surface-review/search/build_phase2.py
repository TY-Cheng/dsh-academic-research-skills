def clean(text: str) -> str:
    text = re.sub(r"<[^>]+>", " ", text or "")
    text = html.unescape(text)
    return re.sub(r"\s+", " ", text).strip()


def fmt_author(name: str) -> str:
    name = re.sub(r"\s+", " ", name.strip())
    special = {
        "Anagha S": "Anagha, S.",
        "Imen Ben Tahar": "Ben Tahar, I.",
        "Victor Ginart Belmonte": "Ginart Belmonte, V.",
        "Cindy Long Yu": "Yu, C. L.",
        "Matthias Reginald Fengler": "Fengler, M. R.",
    }
    if name in special:
        return special[name]
    parts = name.split()
    if len(parts) == 1:
        return name
    surname = parts[-1]
    initials = " ".join(p[0] + "." for p in parts[:-1] if p)
    return f"{surname}, {initials}"


