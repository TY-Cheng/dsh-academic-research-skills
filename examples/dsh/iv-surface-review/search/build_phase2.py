def citation(idx: int) -> str:
    r = RECORDS[idx - 1]
    names = [fmt_author(a) for a in authors_of(idx)]
    if not names:
        auth = "Anonymous"
    elif len(names) == 1:
        auth = names[0]
    elif len(names) == 2:
        auth = f"{names[0]}, & {names[1]}"
    else:
        auth = ", ".join(names[:-1]) + ", & " + names[-1]
    title = TITLE_FIX.get(idx, clean(r.get("title") or "")).rstrip(".")
    venue = VENUE_FIX.get(idx, r.get("venue") or r.get("type") or "")
    doi = r.get("doi") or ""
    if doi:
        link = f"https://doi.org/{doi}"
    else:
        oid = (r.get("openalex_id") or "").rstrip("/").split("/")[-1]
        link = f"https://openalex.org/{oid}"
    return f"{auth} ({year_of(idx)}). {title}. *{venue}*. {link}"


def short(idx: int) -> str:
    names = [fmt_author(a).split(",")[0] for a in authors_of(idx)]
    if not names:
        names = ["Anonymous"]
    if len(names) == 1:
        who = names[0]
    elif len(names) == 2:
        who = f"{names[0]} & {names[1]}"
    else:
        who = f"{names[0]} et al."
    return f"{who} ({year_of(idx)})"


def key_findings(idx: int) -> str:
    if idx in KEY_FINDINGS_FIX:
        return KEY_FINDINGS_FIX[idx]
    if idx == 14:
        return (
            "Abstract not retrieved; title-level only. The title indicates a deep-learning "
            "approach to volatility-surface construction/calibration, but no finding is asserted "
            "here beyond that title-level relevance."
        )
    text = clean(RECORDS[idx - 1].get("abstract") or "")
    if not text:
        return "Abstract unavailable; title-level only."
    sentences = re.split(r"(?<=[.!?])\s+", text)
    chosen: list[str] = []
    for sentence in sentences:
        s = sentence.strip()
        if not s or s.lower().startswith("abstract"):
            continue
        if len(s) < 25:
            continue
        chosen.append(s)
        if len(" ".join(chosen)) >= 380:
            break
    out = " ".join(chosen)
    if len(out) > 560:
        out = out[:557].rsplit(" ", 1)[0] + "..."
    return out


